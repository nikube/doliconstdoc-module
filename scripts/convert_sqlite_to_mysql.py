#!/usr/bin/env python3
"""Convert SQLite constants.sql dump (from doliconstdoc) to MariaDB-compatible
INSERTs targeting llx_doliconstdoc_constants. Drops content_hash, hash_version,
last_enriched, evidence columns (not in the module schema).

Usage:
  python3 convert_sqlite_to_mysql.py SOURCE.sql > data/doliconstdoc.sql
"""
from __future__ import annotations
import sqlite3
import sys
from pathlib import Path

SRC_DEFAULT = Path("/home/nzaou/work/dev/doliconstdoc/doliconstdoc.sqlite")

KEEP = [
    "name", "type", "default_value", "module", "purpose", "description",
    "impact", "possible_values", "hidden_setting", "hidden_setting_guess",
    "admin_ui_files", "conf_php_wiring", "doc_quality", "confidence",
]


def mysql_escape(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    s = s.replace("\\", "\\\\").replace("'", "''")
    return "'" + s + "'"


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC_DEFAULT
    if not src.is_file():
        print(f"missing: {src}", file=sys.stderr)
        sys.exit(2)
    con = sqlite3.connect(str(src))
    cur = con.cursor()
    cols = ", ".join(KEEP)
    out = sys.stdout
    out.write("-- Generated by scripts/convert_sqlite_to_mysql.py\n")
    out.write("-- Source: " + str(src) + "\n")
    rows = cur.execute(f"SELECT {cols} FROM constants ORDER BY name")
    for r in rows:
        vals = ", ".join(mysql_escape(v) for v in r)
        out.write(
            f"INSERT INTO llx_doliconstdoc_constants ({cols}) VALUES ({vals});\n"
        )
    con.close()


if __name__ == "__main__":
    main()
